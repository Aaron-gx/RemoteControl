# 1) 厂商运维文档：新增一节
p = "docs/运维-授权与防绕过.md"
s = io.open(p, encoding="utf-8").read()
anchor = "## 四、界面呈现约定（重要）"
assert anchor in s
section = r"""## 四、离线宽限（"必须联网"策略）

**规则**：被控端**连续 48 小时联系不上中继**就停机（停采集/杀 Worker/断直连/拒新握手）；
一旦能连上，中继会下发当前激活码，被控端**自动恢复**，不需要人工干预。

为什么要有它：被控端本地只认激活码里的到期时间（这是为了"断网也能独立判到期"）。
副作用是——**把网线一拔、或者屏蔽中继只走 P2P，就能把一张已被撤销/已被改短的授权
一直用到它原来的到期时间**。宽限把这件事收敛到有界时间内：任何撤销或续期，
最多 48 小时一定生效。

| 配置项 | 位置 | 默认 | 说明 |
|---|---|---|---|
| `MaxOfflineHours` | 被控端 `config\agent.json` | `48` | 多久联系不上服务器就停机；`0` = 不限制（旧行为） |

判定与恢复细节：

- **什么算"联系上"**：中继 WebSocket 连上，或 `/api/license` 探测成功（每 60 秒一轮）。
- **什么算"联系不上"**：两者都失败——注意这只影响**是否停机**，探测失败本身不会停机。
- **解锁条件**：只有"服务器下发的激活码本机复验通过"才解锁（`UpdateFromServer`）。
  也就是"能继续用"永远意味着"服务器刚刚确认过这张授权"。
- **重启不能重置宽限**：首次运行时间与最后联系时间都落在 `config\license.cache.json` 里，
  重启/重装程序文件都不会重新计时（除非删掉那个缓存文件，而删了它就没有可用激活码了）。
- **从没连上过的机器也算**：宽限从首次运行时刻起算，装好 48 小时内一次都没连上 → 停机。

对运营的含义：

1. 被控端机器必须**至少每 48 小时能连上一次中继**（正常联网的机器天然满足）。
2. 客户机器长期离线（比如搬走、断网）时被控端会停 —— 但那种状态下**本来也远程控制不了**
   （主控/被控都要经中继建立连接），所以不影响任何可用场景。
3. 想放宽/收紧：改被控端的 `MaxOfflineHours`（改完重启被控端生效）。特殊场景可以设 `0` 关掉。
4. **这条策略需要被控端是新版本**：老版本被控端没有宽限逻辑，得更新程序文件才生效
   （`scripts\deploy-quick.ps1` 或 `update-and-restart-agent.cmd`）。

"""
s = s.replace(anchor, section + anchor, 1)
io.open(p, "w", encoding="utf-8").write(s)
print("运维文档已补离线宽限章节")

