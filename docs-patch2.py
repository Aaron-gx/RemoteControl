r += r"""
## 二十一、第十阶段：离线宽限（"必须联网"策略）

背景：被控端本地只认激活码里的 exp（为了断网也能独立判到期）。副作用是"拔网线/屏蔽中继走 P2P"
就能把旧授权一直用到旧到期时间 —— 厂商提出的场景是"新码有效期比旧码短，旧码仍可能被继续使用"。

### 21.1 实现

| 位置 | 改动 |
|---|---|
| `AppConfig` | 新增 `MaxOfflineHours`（默认 **48**，`0` = 不限制 = 旧行为）与 `MaxOffline` |
| `LicenseGate` | 新增离线宽限判定（`Tick` 最前面，连"从没拿到过激活码"的机器也管）；新增 `NoteServerContact()`；缓存新增 `ContactUnix`/`FirstRunUnix` 并落盘 |
| `LicenseGate` 缓存 | 没有缓存文件时也会**先写一次**（把首次运行时刻落盘）；`Save()` 不再因"还没有激活码"而跳过 —— 否则重启就能重置宽限 |
| `Program`（Coordinator） | 中继连上（`OnRelayConnected`）与 `/api/license` 探测成功都调 `NoteServerContact()`；按配置传入宽限 |

判定与恢复：**联系上** = 中继 WS 连上 或 探测成功；**解锁**只由"服务器下发激活码复验通过"触发
（`UpdateFromServer`），保证"能继续用"永远意味着"服务器刚确认过授权"。停机动作复用既有 `LockDown`
（停采集/杀 Worker/断直连/拒新握手），联网后 60 秒内自动恢复。

### 21.2 验证

| 项目 | 结果 |
|---|---|
| C# 单元测试 | ✅ **75/75**（新增 6 项：离线超限启动即判停 + 重新联系后仅"联系"不解锁、服务器下发激活码才恢复 / 宽限内不停机 / `0` 时不启用（向后兼容）/ 从没联系过按首次运行起算 / **首次运行时间落盘且重启不重置** / 联系成功会刷新落盘时间） |
| 被控端构建 | ✅ `build\agent` 已更新（含宽限逻辑） |
| 安装包 | ✅ 重新打包（新装的机器直接带宽限策略） |

### 21.3 边界与运营

- 被控端机器需**至少每 48 小时能连上一次中继**；正常联网的机器天然满足。
- 客户机器长期离线时被控端会停 —— 但那种状态下本来就远程控制不了（连接必须经中继建立），
  不影响任何可用场景，且**联网后自动恢复**，不需要人工处理。
- **老版本被控端没有这条逻辑**，要更新程序文件才生效（`scripts\deploy-quick.ps1` / `update-and-restart-agent.cmd`）。
"""
